test('the badge follows verified official discounts and retains the last result offline', async ({ page }) => {
  await page.goto('/?scene=idle')
  await page.getByRole('button', { name: /DeepSeek 空闲期/ }).click()
  await page.getByRole('button', { name: /查看计费说明/ }).hover()
  const card = page.getByRole('region', { name: '计费说明', exact: true })
  await expect(card).toContainText('已同步官网')
  const changed = structuredClone(BUNDLED_PRICING)
  changed.checkedAt = Date.now()
  for (const model of changed.models) {
    for (const key of ['inputHit', 'inputMiss', 'output'] as const) model.idle[key] = model.peak[key] * 0.75
  }
  await page.route('**/__dsh-fg/pricing**', route => route.fulfill({ json: changed }))
  await page.getByRole('button', { name: '立即同步', exact: true }).click()
  await expect(page.getByRole('button', { name: '价格下降 25%，查看计费说明', exact: true })).toBeVisible()
  await page.route('**/__dsh-fg/pricing**', route => route.fulfill({ status: 502, json: { error: 'offline' } }))
  await page.getByRole('button', { name: '立即同步', exact: true }).click()
  await expect(card).toContainText('暂未同步成功')
  await expect(page.getByRole('button', { name: '价格下降 25%，查看计费说明', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /DeepSeek 空闲期/ }).click()
  await expect(page.getByRole('button', { name: '价格下降 25%，查看计费说明', exact: true })).toBeVisible()
})

