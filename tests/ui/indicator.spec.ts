import { test, expect } from '@playwright/test'
import { BUNDLED_PRICING } from '../../src/pricing.ts'

test.beforeEach(async ({ page }) => {
  await page.route('**/__dsh-fg/pricing**', route => route.fulfill({ json: { ...BUNDLED_PRICING, checkedAt: Date.now() } }))
})

test('the toolbar shows only an icon and duration; blue selection toggles on and off', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/?scene=peak&theme=light')
  const trigger = page.getByRole('button', { name: /DeepSeek 繁忙期/ })
  await expect(trigger).toHaveText(/^2h \d+m$/)
  const inactiveColor = await trigger.evaluate(el => getComputedStyle(el).color)
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'DeepSeek 价格与时段' })
  await expect(dialog).toBeVisible()
  const dshBlue = await trigger.evaluate(el => getComputedStyle(el).getPropertyValue('--dsw-alias-state-business-primary').trim())
  await expect(trigger).toHaveCSS('color', dshBlue)
  expect(dshBlue).not.toBe(inactiveColor)
  await expect(dialog.getByRole('button', { name: /关闭/ })).toHaveCount(0)
  await expect(dialog.getByRole('region')).toHaveCount(0)
  await expect(dialog).not.toContainText('DEEPSEEK')
  await expect(dialog).not.toContainText('按本机时间判断')
  await expect(dialog).toContainText('繁忙期价格')
  await expect(dialog).not.toContainText('缓存命中')
  await expect(dialog.getByRole('button', { name: 'Flash', exact: true })).toHaveCount(0)
  const earlier = await page.locator('.dsh-fg__countdown').innerText()
  await expect(page.locator('.dsh-fg__countdown')).not.toHaveText(earlier, { timeout: 2500 })
  await trigger.click()
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await trigger.click()
  await page.locator('.preview-mark').click()
  await expect(dialog).not.toBeVisible()
  expect(errors).toEqual([])
})

