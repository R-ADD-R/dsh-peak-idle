test('small dark windows keep the duration, panel and secondary information in the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 720 })
  await page.goto('/?scene=idle&theme=dark')
  const trigger = page.getByRole('button', { name: /DeepSeek 空闲期/ })
  await expect(trigger.locator('.dsh-fg__duration')).toBeVisible()
  await trigger.click()
  for (const item of [page.getByRole('dialog')]) {
    const bounds = await item.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(12)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(363)
    expect(bounds!.y).toBeGreaterThanOrEqual(12)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(708)
  }
  const bg = await page.getByRole('dialog').evaluate(el => getComputedStyle(el).backgroundColor)
  expect(bg).not.toBe('rgb(255, 255, 255)')
  await page.getByRole('button', { name: '查看时段详情', exact: true }).click()
  const bounds = await page.getByRole('region', { name: '时段详情', exact: true }).boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(12)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(363)
  expect(bounds!.y).toBeGreaterThanOrEqual(12)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(708)
  await page.getByRole('switch').uncheck()
  await expect(page.getByRole('switch')).not.toBeChecked()
})

test('keyboard focus reaches secondary controls and Escape dismisses each layer', async ({ page }) => {
  await page.goto('/?scene=peak')
  const trigger = page.getByRole('button', { name: /DeepSeek 繁忙期/ })
  await page.getByRole('textbox').fill('保留的草稿')
  await trigger.focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: /查看计费说明/ })).toBeFocused()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '查看时段详情', exact: true })).toBeFocused()
  await expect(page.getByRole('region', { name: '时段详情', exact: true })).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('switch', { name: '时段切换提醒' })).toBeFocused()
  await page.keyboard.press('Space')
  await expect(page.getByRole('switch')).not.toBeChecked()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('region')).toHaveCount(0)
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('textbox')).toHaveValue('保留的草稿')
})

